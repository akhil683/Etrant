import { NextRequest, NextResponse } from "next/server";
import { and, asc, desc, gte, lte } from "drizzle-orm";
import { db } from "@/lib/db/db";
import { questions } from "@/lib/db/schema";
import { generateQuestionPrompt } from "@/lib/prompts/generate-questions";
import { AIQuestions } from "@/lib/repositories/question-repository";
import { InterestCategory } from "@/types";
import { requireUser } from "@/lib/auth/request-user";
import { getSubscriptionStatus } from "@/lib/subscription";

export const dynamic = "force-dynamic";

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;
const DEFAULT_DAYS = 30;
const MAX_LIMIT = 50;

function localIsoDate(daysAgo = 0) {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  const yyyy = date.getFullYear();
  const mm = String(date.getMonth() + 1).padStart(2, "0");
  const dd = String(date.getDate()).padStart(2, "0");
  return `${yyyy}-${mm}-${dd}`;
}

/**
 * Questions for a date range. The app uses this for the reel and for the
 * "last 7 / 30 / 90 days" filter. Questions are generated by the nightly
 * digest cron, never by this endpoint.
 */
export async function GET(request: NextRequest) {
  try {
    const authResult = await requireUser(request);
    if ("response" in authResult) return authResult.response;

    const status = await getSubscriptionStatus(authResult.user.id);
    if (!status.active) {
      return NextResponse.json(
        { error: "Subscription required.", code: "SUBSCRIPTION_REQUIRED" },
        { status: 403 },
      );
    }

    const { searchParams } = new URL(request.url);
    const from = searchParams.get("from") ?? localIsoDate(DEFAULT_DAYS);
    const to = searchParams.get("to") ?? localIsoDate();
    const limit = Math.min(
      Math.max(Number.parseInt(searchParams.get("limit") ?? "20", 10) || 20, 1),
      MAX_LIMIT,
    );
    const offset = Math.max(
      Number.parseInt(searchParams.get("offset") ?? "0", 10) || 0,
      0,
    );

    if (!ISO_DATE.test(from) || !ISO_DATE.test(to)) {
      return NextResponse.json(
        { error: "from and to must use YYYY-MM-DD." },
        { status: 400 },
      );
    }

    if (from > to) {
      return NextResponse.json(
        { error: "from must be before to." },
        { status: 400 },
      );
    }

    const rows = await db
      .select({
        id: questions.id,
        digestDate: questions.digestDate,
        position: questions.position,
        question: questions.question,
        difficulty: questions.difficulty,
        category: questions.category,
        tags: questions.tags,
        context: questions.context,
        estimatedTime: questions.estimatedTime,
        options: questions.options,
        correctAnswer: questions.correctAnswer,
        explanation: questions.explanation,
        metadata: questions.metadata,
      })
      .from(questions)
      .where(
        and(gte(questions.digestDate, from), lte(questions.digestDate, to)),
      )
      .orderBy(desc(questions.digestDate), asc(questions.position))
      .limit(limit)
      .offset(offset);

    return NextResponse.json({
      from,
      to,
      limit,
      offset,
      count: rows.length,
      questions: rows,
    });
  } catch (error) {
    console.error("Failed to load questions:", error);
    return NextResponse.json(
      { error: "Could not load questions." },
      { status: 500 },
    );
  }
}

/**
 * Existing web endpoint: generates practice questions on demand for the AI
 * questions page. The mobile app uses GET instead and never calls the model.
 */
export async function POST(request: NextRequest) {
  try {
    const { interests: category, language } = await request.json();
    if (!category || typeof category !== "string") {
      return NextResponse.json(
        {
          error: "Bad Request",
          message: "Category or language is required and must be a string",
        },
        { status: 400 },
      );
    }

    const prompt = generateQuestionPrompt(
      category as InterestCategory,
      language,
    );
    const generated = await AIQuestions.getAIQuestions(prompt);

    return NextResponse.json({
      success: true,
      data: generated,
      count: generated.length,
      category,
    });
  } catch (error) {
    console.error("API Error:", error);

    return NextResponse.json(
      {
        error: "Internal Server Error",
        message:
          error instanceof Error ? error.message : "Unknown error occurred",
      },
      { status: 500 },
    );
  }
}
